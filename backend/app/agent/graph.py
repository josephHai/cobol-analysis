class ToolBudgetMiddleware(AgentMiddleware):
    """Hard cap on tool calls so one runaway run cannot exhaust the budget.

    The limit is a correctness guard, not an optimisation: without it a model
    stuck in a read loop would keep spending until the wall-clock cap fires.

    The budget is **per agent invocation**, and a run makes up to four of them (one analysis,
    three deliverables), so ``MAX_TOOL_CALLS`` bounds each invocation rather than the run.
    """

    def __init__(self, max_tool_calls: int) -> None:
        super().__init__()
        self.max_tool_calls = max_tool_calls
        self.used = 0

    def _spend(self) -> None:
        """Count one call, and refuse the call that exceeds the budget."""
        self.used += 1
        if self.used > self.max_tool_calls:
            raise RuntimeError(
                f"Tool call budget exhausted ({self.max_tool_calls} calls); "
                "the run was stopped to prevent runaway cost."
            )

    def wrap_tool_call(self, request: Any, handler: Callable[[Any], Any]) -> Any:
        self._spend()
        return handler(request)

    async def awrap_tool_call(self, request: Any, handler: Callable[[Any], Any]) -> Any:
        self._spend()
        return await handler(request)


def build_model(settings: Settings, model_name: str | None = None) -> BaseChatModel:
    """Build the chat model for the configured provider.

    This is the single place the model client is constructed, so switching gateways is a
    configuration change rather than a code change.

    Two providers are supported:

    ``openai``
        ``POST /v1/chat/completions``. The default, and the dialect nearly every hosted and
        self-hosted gateway exposes. Verified against a live gateway: single tool calls,
        **parallel tool calls in one response**, and SSE streaming all work.
    ``anthropic``
        ``POST /v1/messages``. For a gateway that speaks only that dialect.
    Credentials are resolved through :meth:`Settings.resolve_api_key` and never logged.
    """
    resolved = model_name or settings.llm_model
    api_key = settings.resolve_api_key()
    timeout = settings.llm_timeout_seconds

    if settings.llm_provider == "anthropic":
        from langchain_anthropic import ChatAnthropic

        # Field names differ from the OpenAI client: `anthropic_api_url` rather than
        # `base_url` (verified against langchain-anthropic 1.7.1).
        return ChatAnthropic(
            model=resolved,
            anthropic_api_url=settings.llm_base_url or None,
            anthropic_api_key=api_key or None,
            temperature=settings.llm_temperature,
            max_tokens=settings.llm_max_tokens,
            default_request_timeout=timeout,
            max_retries=2,
        )

    return ChatOpenAI(
        model=resolved,
        base_url=settings.llm_base_url,
        api_key=api_key or "not-required",
        temperature=settings.llm_temperature,
        max_retries=2,
        timeout=timeout,
        stream_usage=True,
    )


def default_permissions() -> list[FilesystemPermission]:
    """Path rules enforced by the filesystem middleware before any IO happens.

    One builder for the whole project: these rules are asserted by the security tests, and a
    second copy of the route table elsewhere is how "the tests pass on wiring the app does not
    use" happens.
    """
    return [
        # The checkout is evidence, never a scratch pad. This covers the whole tree, including
        # the `.git` pointer file a worktree carries — a rule written as `/.git/**` would never
        # match anything, because the agent's virtual paths all start with a route prefix.
        FilesystemPermission(operations=["write"], paths=["/repo/**"], mode="deny"),
        FilesystemPermission(operations=["delete"], paths=["/repo/**"], mode="deny"),
        # The skill library is read-only reference material.
        FilesystemPermission(operations=["write"], paths=["/skills/**"], mode="deny"),
        FilesystemPermission(operations=["delete"], paths=["/skills/**"], mode="deny"),
        # Never read credential-shaped files, even if a repository ships one.
        FilesystemPermission(operations=["read"], paths=["/**/.env*"], mode="deny"),
        FilesystemPermission(operations=["read"], paths=["/**/secrets/**"], mode="deny"),
        FilesystemPermission(operations=["read"], paths=["/**/*.pem"], mode="deny"),
        FilesystemPermission(operations=["read"], paths=["/**/id_rsa*"], mode="deny"),
    ]


def build_backend_with_skills(
    settings: Settings, run_root: str
) -> tuple[CompositeBackend, list[str]]:
    """Build the agent backend, mounting the skill library at ``/skills`` when available.

    Returns ``(backend, skill_sources)`` where ``skill_sources`` is what must be passed to
    ``create_deep_agent(skills=...)`` — empty when skills are unavailable, so the caller can
    pass it straight through and get a skill-less but working agent.

    **Verified routing semantics** (deepagents 0.7.13, established by probing rather than
    assuming): ``CompositeBackend`` strips the *entire* route prefix and hands the remainder to a
    backend rooted at the route's ``root_dir``. The remainder can therefore be empty, and a
    one-segment prefix like ``/analysis/`` cannot be made to preserve its own segment. Each route
    below therefore pairs a prefix with the directory it should resolve *to*:

    * ``/work/x`` + root ``<run>/work`` → ``<run>/work/x``
    * ``/artifacts/fdd.md`` + root ``<run>/artifacts`` → ``<run>/artifacts/fdd.md``
    * ``/repo/x`` + root ``<run>/repo`` → ``<run>/repo/x``

    That is why the analysis hand-off lives at ``/work/analysis.json`` rather than under a nested
    ``/analysis/``: an earlier revision used ``/analysis/analysis.json`` with that route pointed at
    the run root, so the model wrote ``<run>/analysis.json`` while the pipeline looked for
    ``<run>/analysis/analysis.json`` and reported "the analysis skill did not produce …" for a file
    that existed.

    ``/repo`` gets its own backend instance so read-only intent is expressed in the wiring, not
    only in the permission list.

    ``/skills`` is mounted here too, and that is not optional: ``SkillsMiddleware`` resolves its
    sources **through the backend**, not through the host filesystem. A path that is not reachable
    as a route simply does not exist as far as skill loading is concerned, which is what made an
    earlier revision silently run with no skills at all despite the directory being present on disk.

    **The source path must match the backend that resolves it.** Also verified against
    deepagents 0.7.13: probing a backend rooted at the skills directory with source ``"/skills/"``
    fails with ``path_not_found`` (the prefix is addressed against that backend's own root), while
    ``"/"`` loads every skill. The route below is therefore keyed ``"/skills/"`` against a root of
    ``<skills_dir>``, which is the combination that yields ``/skills/<name>/SKILL.md`` from the
    agent's point of view.
    """
    root = Path(run_root)
    routes: dict[str, Any] = {
        "/repo/": FilesystemBackend(root_dir=root / "repo", virtual_mode=True),
        "/work/": FilesystemBackend(root_dir=root / "work", virtual_mode=True),
        "/artifacts/": FilesystemBackend(root_dir=root / "artifacts", virtual_mode=True),
    }
    sources: list[str] = []

    if settings.skills_enabled and settings.skills_dir.is_dir():
        routes["/skills/"] = FilesystemBackend(root_dir=settings.skills_dir, virtual_mode=True)
        sources = ["/skills/"]
    elif settings.skills_enabled:
        logger.error(
            "skills directory %s does not exist; running without skills. "
            "Set SKILLS_DIR, or SKILLS_ENABLED=false to silence this.",
            settings.skills_dir,
        )

    backend = CompositeBackend(
        default=FilesystemBackend(root_dir=root / "work", virtual_mode=True),
        routes=routes,
    )
    return backend, sources


def build_agent(
    settings: Settings,
    *,
    run_root: str,
    system_prompt: str,
    model_name: str | None = None,
) -> Any:
    """Create the lead agent for one run.

    The result is a compiled LangGraph state graph, so ``astream_events``, checkpointing and
    interrupts work without further plumbing.

    ``skills=`` is what actually enables skill loading: ``create_deep_agent`` only attaches
    ``SkillsMiddleware`` when the argument is non-empty, so omitting it produces an agent
    that silently has no skills however many ``SKILL.md`` files exist on disk.
    """
    # TODO(demo): approvals are backend-only and not wired; `interrupt_on` is unused
    # (docs/DEMO.md §7 gap 6). Nothing on the demo path needs an interrupt.
    backend, sources = build_backend_with_skills(settings, run_root)
    if sources:
        logger.debug("skills mounted from %s at %s", settings.skills_dir, sources)
    return create_deep_agent(
        model=build_model(settings, model_name),
        backend=backend,
        system_prompt=system_prompt,
        skills=sources or None,
        permissions=default_permissions(),
        middleware=[ToolBudgetMiddleware(settings.max_tool_calls)],
        name="cobol-analysis",
    )


#: Note for anyone debugging prompts: the ``KEY=value`` markers below are stable,
#: machine-readable run parameters. Diagnostics depend on them, so keep them one-per-line
#: and keep the names.
#:
#: Prompt-templating contract — keep this here, **never inside the prompt text**:
#:
#: * ``ANALYSIS_PROMPT`` uses only ``str.format`` fields, so literal braces are doubled.
#: * ``ARTIFACT_PROMPT`` mixes ``string.Template`` placeholders (``$label``, ``$skill``) with
#:   ``str.format`` fields (``{run_root}`` …). Render it through
#:   ``app.agent.pipeline._render_artifact_prompt``.
#:
#: **The procedure lives in the SKILL.md files, not here.** These prompts only supply run
#: parameters and point at the skill to follow. That split is what makes a procedure
#: editable without a deploy, versionable on its own, and visible to the agent through
#: progressive disclosure. Duplicating it into the prompt would create two sources of truth
#: that drift — the state this refactor removed.
#:
#: **Never write implementation notes, function names or template mechanics into the prompt
#: text itself.** A revision did exactly that, and the model — reasonably — went looking for
#: ``app.agent.pipeline`` inside its sandbox, failed, and then narrated the failure into the
#: generated FDD.
