"""Agent construction: one lead agent per run, wired to that run's sandbox directory.

Everything the agent may touch is expressed as a backend route, so it has genuine
filesystem access (read, scan, write) while staying boxed inside
``<data_root>/runs/<run_id>``:

===========================  ==========================================
Virtual path                 Backend / mode
===========================  ==========================================
``/repo/**``                 read-only checkout of the pinned commit
``/work/**``                 writable scratch space for the skills
``/artifacts/**``            writable final deliverables
``/work/analysis.json``      hand-off between the two pipeline stages
===========================  ==========================================

``virtual_mode=True`` is mandatory. It rejects ``..`` and ``~``, and verifies the
resolved path stays under the root — which also defeats symlink escapes, because
resolution happens before the containment check.

No backend here implements ``SandboxBackendProtocol``, so the ``execute`` tool is
never offered to the model. That is the primary reason the agent cannot reach a
host shell (see CODESTYLE.md hard rule S1).
"""

