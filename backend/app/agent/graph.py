#: The three deliverables, each generated by an independent agent invocation.
#:
#: ``skill`` is the **directory name** of the skill that defines the procedure, and the two
#: namespaces differ on purpose, which is worth stating because it has already caused one
#: silent failure:
#:
#: * the key (``test_case``) is an API/artifact identity — it appears in ``Run.skills``, in
#:   the REST contract and in the console's URL, so it must not change casually;
#: * ``skill`` is the on-disk skill name, which follows the Agent Skills convention of
#:   lowercase hyphenated words (``test-case``), matching its ``SKILL.md`` frontmatter.
#:
#: ``filename`` is the deliverable as it lands in ``<run>/artifacts``: the pipeline writes it, the
#: console downloads it by that name, and ``skills-check`` prints it. One entry, one name.
#:
#: The pipeline keeps invoking these programmatically rather than letting the lead agent
#: choose: "the three deliverables always generate, in parallel, with isolated failures" is a
#: product guarantee, and making it depend on the model's discretion would trade a guarantee
#: for a hope. The skills still supply the entire procedure — see ``_render_artifact_prompt``.
#: ``accepts`` declares the deliverable format the code can persist, and it is the single most
#: likely thing to break when a skill is replaced. The pipeline reads the model's *reply*: Markdown
#: is written straight to disk, and ``json_rows`` is parsed out of a fenced JSON block and rendered
#: into a workbook. A skill that returns something else — a document for the FDD, or a workbook
#: produced by a script — needs either this table changed or that skill adapted. Failure is loud
#: and isolated per deliverable, but `python scripts/dev.py skills-check` catches it in seconds
#: instead of at the end of a 90-second run.
