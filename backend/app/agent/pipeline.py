"""Run pipeline: the end-to-end analysis workflow.

Phase order (mirrors ``docs/DESIGN.md`` §1.1)::

    fetch -> index -> analyze -> generate (fan-out x3) -> validate -> archive -> kb

Four decisions worth stating explicitly, because they are what make this
predictable enough to demo live:

1. **The three deliverables are fanned out by code, not by the model.** The lead
   agent plans and produces the intermediate analysis; the deliverables are then
   generated by three independent agent invocations driven by ``asyncio.gather``
   with a semaphore. "Parallel, isolated, individually retryable" becomes a
   property of the code rather than a hope about model behaviour.
2. **One failing branch never fails the run.** ``return_exceptions=True`` means a
   failed deliverable is marked failed while the others still land.
3. **Every artifact is validated before it is announced.** A deliverable that
   cannot be parsed is a failed deliverable, not a ready one.
4. **Blocking agent calls run in a worker thread.** ``astream_events`` is a sync
   generator; running it in the event loop would stall the SSE stream and make the
   live progress bar lie about what is happening.

All emitted event names and payload keys are part of the SSE contract consumed by
the web client (``docs/DESIGN.md`` §4.4).
"""

